// Starts / stops the local Worker for the QA suite: QA entry (qa/worker-entry.ts) on a FRESH local D1
// (temporary --persist-to directory inside the worktree, migrations applied first) and a fake
// Telegram Bot API, so notifications never leave the machine.
//
// Env:
//   QA_PORT          worker port (default 8797 — other agents use 8787)
//   QA_TG_PORT       fake Telegram API port (default 8798)
//   QA_INSPECTOR     inspector port (default 9339)
//   BASE             use an ALREADY RUNNING QA worker at this URL instead of starting one
import { spawn, execFileSync } from 'node:child_process';
import fs from 'node:fs';
import http from 'node:http';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const WORKER_DIR = path.join(ROOT, 'apps', 'worker');
export const RUN_DIR = path.join(ROOT, 'qa', '.run');
export const PORT = Number(process.env.QA_PORT || 8797);
export const TG_PORT = Number(process.env.QA_TG_PORT || 8798);
const INSPECTOR = Number(process.env.QA_INSPECTOR || 9339);
export const TEST_KEY = 'qa-test-key';
export const BOT_TOKEN = '123456789:qa-fake-token';
export const SETUP_KEY = 'qa-setup-key';
export const WEBHOOK_SECRET = 'qa-webhook-secret';

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

// ------------------------------------------------------------ fake Telegram Bot API

export const telegram = { calls: [], server: null, failSend: true };

export function startFakeTelegram() {
  if (telegram.server) return Promise.resolve();
  telegram.server = http.createServer((req, res) => {
    let body = '';
    req.on('data', (d) => (body += d));
    req.on('end', () => {
      const m = /\/bot[^/]+\/(\w+)/.exec(req.url || '');
      const method = m ? m[1] : '?';
      let payload = {};
      try { payload = JSON.parse(body || '{}'); } catch { payload = { raw: body }; }
      telegram.calls.push({ method, payload, at: Date.now() });
      const ok = (result) => { res.writeHead(200, { 'content-type': 'application/json' }); res.end(JSON.stringify({ ok: true, result })); };
      if (method === 'getMe') return ok({ id: 7000000001, is_bot: true, first_name: 'QA bot', username: 'qa_honey_bot' });
      if (method === 'sendMessage' && telegram.failSend) {
        // Default: every message fails like a user who blocked the bot — notifications must never break requests.
        res.writeHead(403, { 'content-type': 'application/json' });
        return res.end(JSON.stringify({ ok: false, error_code: 403, description: 'Forbidden: bot was blocked by the user' }));
      }
      if (method === 'sendMessage') return ok({ message_id: telegram.calls.length, chat: { id: payload.chat_id }, text: payload.text });
      if (method === 'getWebhookInfo') return ok({ url: 'https://qa.example/telegram/webhook', pending_update_count: 0 });
      return ok(true);
    });
  });
  return new Promise((r) => telegram.server.listen(TG_PORT, '127.0.0.1', r));
}

export function stopFakeTelegram() {
  if (telegram.server) telegram.server.close();
  telegram.server = null;
}

// ------------------------------------------------------------ wrangler config + dev server

function writeConfig({ testMode = '1', cronMax = 100, publicUrl = '', testUsers = '', deployEnv = '' } = {}) {
  fs.mkdirSync(RUN_DIR, { recursive: true });
  const abs = (p) => JSON.stringify(path.join(ROOT, p));
  const toml = `# generated by qa/lib/worker.mjs — QA only, never deployed
name = "honey-loyalty-qa"
main = ${abs('qa/worker-entry.ts')}
compatibility_date = "2026-09-30"

[alias]
"@honey/core" = ${abs('packages/core/src/index.ts')}
"@honey/service" = ${abs('packages/service/src/index.ts')}

[assets]
directory = ${abs('apps/miniapp/dist')}
binding = "ASSETS"
not_found_handling = "single-page-application"
run_worker_first = ["/api/*", "/telegram/*", "/setup", "/health", "/__qa/*"]

[[d1_databases]]
binding = "DB"
database_name = "honey-loyalty-qa"
database_id = "00000000-0000-0000-0000-000000000000"
migrations_dir = ${abs('apps/worker/migrations')}

[vars]
TEST_MODE = "${testMode}"
BOT_USERNAME = "qa_honey_bot"
TELEGRAM_API_BASE = "http://127.0.0.1:${TG_PORT}"
CRON_MAX_CLIENTS = "${cronMax}"
TEST_USERS = "${testUsers}"
${deployEnv ? `DEPLOY_ENV = "${deployEnv}"` : ''}
${publicUrl ? `PUBLIC_URL = "${publicUrl}"` : ''}
`;
  fs.writeFileSync(path.join(RUN_DIR, 'wrangler.qa.toml'), toml);
  fs.writeFileSync(
    path.join(RUN_DIR, '.dev.vars'),
    `BOT_TOKEN=${BOT_TOKEN}\nWEBHOOK_SECRET=${WEBHOOK_SECRET}\nSETUP_KEY=${SETUP_KEY}\nTEST_KEY=${TEST_KEY}\n`,
  );
  return path.join(RUN_DIR, 'wrangler.qa.toml');
}

const wranglerBin = path.join(ROOT, 'node_modules', '.bin', 'wrangler');

export const worker = { proc: null, persist: null, base: process.env.BASE || null, external: !!process.env.BASE, log: [] };

/** Fresh persist dir + migrations. */
export function freshDatabase() {
  const persist = path.join(RUN_DIR, `d1-${Date.now()}`);
  fs.mkdirSync(persist, { recursive: true });
  const cfg = writeConfig();
  execFileSync(wranglerBin, ['d1', 'migrations', 'apply', 'DB', '--local', '--persist-to', persist, '--config', cfg], {
    cwd: WORKER_DIR, stdio: ['ignore', 'pipe', 'pipe'], env: { ...process.env, CI: '1' },
  });
  worker.persist = persist;
  return persist;
}

export async function startWorker(opts = {}) {
  if (worker.external) return worker.base;
  await startFakeTelegram();
  if (!worker.persist || opts.fresh) freshDatabase();
  const cfg = writeConfig(opts);
  const args = ['dev', '--config', cfg, '--port', String(PORT), '--ip', '127.0.0.1', '--persist-to', worker.persist,
    '--inspector-port', String(INSPECTOR), '--show-interactive-dev-session=false', '--log-level', 'warn'];
  worker.log = [];
  worker.proc = spawn(wranglerBin, args, { cwd: RUN_DIR, env: { ...process.env, CI: '1', WRANGLER_SEND_METRICS: 'false' }, stdio: ['ignore', 'pipe', 'pipe'], detached: true });
  const keep = (d) => { worker.log.push(String(d)); if (worker.log.length > 2000) worker.log.shift(); };
  worker.proc.stdout.on('data', keep);
  worker.proc.stderr.on('data', keep);
  worker.base = `http://127.0.0.1:${PORT}`;
  for (let i = 0; i < 240; i++) {
    if (worker.proc.exitCode !== null) throw new Error('wrangler dev exited:\n' + worker.log.join('').slice(-3000));
    try {
      const r = await fetch(worker.base + '/health');
      if (r.ok) return worker.base;
    } catch { /* not yet */ }
    await sleep(250);
  }
  throw new Error('wrangler dev did not start on :' + PORT + '\n' + worker.log.join('').slice(-3000));
}

export async function stopWorker() {
  if (!worker.proc) return;
  const p = worker.proc;
  worker.proc = null;
  try { process.kill(-p.pid, 'SIGTERM'); } catch { /* gone */ }
  for (let i = 0; i < 40 && p.exitCode === null && p.signalCode === null; i++) await sleep(100);
  try { process.kill(-p.pid, 'SIGKILL'); } catch { /* gone */ }
  // wait until the port is free
  for (let i = 0; i < 40; i++) {
    try { await fetch(`http://127.0.0.1:${PORT}/health`); await sleep(150); } catch { break; }
  }
}

export async function restartWorker(opts = {}) {
  await stopWorker();
  return startWorker(opts);
}

process.on('exit', () => { if (worker.proc) try { process.kill(-worker.proc.pid, 'SIGKILL'); } catch { /* */ } });
for (const sig of ['SIGINT', 'SIGTERM']) process.on(sig, () => { if (worker.proc) try { process.kill(-worker.proc.pid, 'SIGKILL'); } catch { /* */ } process.exit(130); });
