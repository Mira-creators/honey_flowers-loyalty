import { LoyaltyError } from '../errors.js';
import type { LoyaltyEvent } from '../events.js';
import { mulDiv, percentOf } from '../money.js';
import { applyOutcome, emptyOutcome, mergeOutcomes, type Outcome } from '../outcome.js';
import type { LoyaltyRules } from '../rules.js';
import {
  activeCardMoves,
  balanceFromLedger,
  cardPosition,
  deriveLevel,
  purchasesToNextReward,
  rewardsForCycle,
} from '../state.js';
import { localDateKey } from '../time.js';
import type { CardMove, Channel, ClientState, PurchaseLine, PurchaseRecord, PurchaseSummary, Reward, Uzs } from '../types.js';
import { assert, eligibleTotal, findAvailableReward, redeemCap, rewardEffect, validateLines } from './common.js';
import { settleExpiry } from './expiry.js';

export interface PurchaseInput {
  /** Storage id of the new purchase (generated by the caller, e.g. UUID). */
  purchaseId: string;
  /** Client-generated key; resubmitting the same key replays the first result. */
  idempotencyKey: string;
  staffId: string | null;
  lines: PurchaseLine[];
  channel: Channel;
  /** Points (мёд) the client pays with. Default 0. */
  redeemPoints?: Uzs;
  /** An available gift (from the client's "Подарки") to use in this order. */
  useRewardId?: string | null;
}

/** Stable reward id: the same cell can be unlocked again after a reversal. */
export function rewardId(cycle: number, cell: number, purchaseId: string): string {
  return `${cycle}-${cell}-${purchaseId}`;
}

/** Card moves made by purchases on the same local calendar day as `now`. */
export function cellMovesOnDay(rules: LoyaltyRules, state: ClientState, now: Date): number {
  const today = localDateKey(now, rules.timezone);
  return activeCardMoves(state).filter(
    (m) => m.reason === 'purchase' && localDateKey(m.createdAt, rules.timezone) === today,
  ).length;
}

/**
 * How many points the client may spend on an order (for the staff UI):
 * min(balance, maxRedeemPct of the order, order minus gift discount).
 */
export function maxRedeemable(
  rules: LoyaltyRules,
  state: ClientState,
  lines: readonly PurchaseLine[],
  rewardIdToUse: string | null = null,
): Uzs {
  const amount = lines.reduce((s, l) => s + l.amount, 0);
  const reward = rewardIdToUse ? state.rewards.find((r) => r.id === rewardIdToUse) ?? null : null;
  if (reward?.type === 'discount_pct' && !rules.allowDiscountWithPoints) return 0;
  const discount = rewardEffect(reward, lines, amount).discount;
  return Math.max(0, Math.min(balanceFromLedger(state.ledger), redeemCap(rules, amount, discount)));
}

function sameRequest(p: PurchaseRecord, input: PurchaseInput, amount: Uzs): boolean {
  return (
    p.amount === amount &&
    p.pointsRedeemed === (input.redeemPoints ?? 0) &&
    (p.rewardUsedId ?? null) === (input.useRewardId ?? null)
  );
}

/**
 * Register a purchase: optional reward and points redemption, cashback
 * accrual, honeycomb step, gifts and level change.
 *
 * Order of evaluation:
 *  1. idempotency replay;
 *  2. overdue expiry is settled first (a late scheduler cannot save points);
 *  3. reward discount, then points (cap: maxRedeemPct of the gross amount);
 *  4. cashback = level-before % of the PAID part of eligible categories;
 *  5. card step if amount >= minPurchaseForCell and daily limit not reached;
 *  6. level after the purchase → `level_up` event (applies from the next one).
 */
export function applyPurchase(rules: LoyaltyRules, state: ClientState, input: PurchaseInput, now: Date): Outcome {
  const amount = validateLines(input.lines);
  assert(input.idempotencyKey, 'INVALID_INPUT', 'idempotencyKey is required');

  // 1. Idempotency: same key → original result, no new effects.
  const prior = state.purchases.find((p) => p.idempotencyKey === input.idempotencyKey);
  if (prior) {
    if (!sameRequest(prior, input, amount)) {
      throw new LoyaltyError('IDEMPOTENCY_CONFLICT', 'idempotencyKey was already used for a different purchase');
    }
    return { ...emptyOutcome(), replayed: true, purchase: prior };
  }

  // 2. Overdue expiry.
  const expiry = settleExpiry(rules, state, now);
  const s = applyOutcome(state, expiry);
  const out = emptyOutcome();
  const clientId = s.clientId;
  const events: LoyaltyEvent[] = [];

  // 3. Reward and points.
  const redeem = input.redeemPoints ?? 0;
  assert(Number.isSafeInteger(redeem) && redeem >= 0, 'INVALID_INPUT', 'redeemPoints must be a non-negative integer');
  const reward = input.useRewardId ? findAvailableReward(s, input.useRewardId) : null;
  if (reward?.type === 'discount_pct' && redeem > 0 && !rules.allowDiscountWithPoints) {
    throw new LoyaltyError('DISCOUNT_WITH_POINTS_NOT_ALLOWED', 'discount gift and points cannot be combined');
  }
  const effect = rewardEffect(reward, input.lines, amount);
  const discount = effect.discount;
  const balanceBefore = balanceFromLedger(s.ledger);
  if (redeem > 0) {
    assert(redeem <= balanceBefore, 'INSUFFICIENT_BALANCE', `balance ${balanceBefore} < ${redeem}`);
    const cap = redeemCap(rules, amount, discount);
    assert(redeem <= cap, 'REDEEM_CAP_EXCEEDED', `at most ${cap} points can be used on this order`);
  }
  const paid = amount - discount - redeem;

  // 4. Cashback on the money-paid part of eligible categories.
  //    A targeted gift (free delivery / card) reduces its own category first;
  //    the % discount and points are spread over the order proportionally.
  const targeted = effect.targetCategory ? discount : 0;
  const eligibleAfterTarget =
    eligibleTotal(rules, input.lines) -
    (effect.targetCategory && rules.cashbackCategories[effect.targetCategory] ? targeted : 0);
  const totalAfterTarget = amount - targeted;
  const cashbackBase = totalAfterTarget > 0 ? mulDiv(eligibleAfterTarget, paid, totalAfterTarget) : 0;
  const levelBefore = deriveLevel(rules, s, now);
  const cashbackPct = levelBefore.tier.cashbackPct;
  const cashback = percentOf(cashbackBase, cashbackPct);

  if (reward) {
    out.rewardsUpdated.push({ ...reward, status: 'used', usedInPurchase: input.purchaseId, usedAt: now });
    events.push({ type: 'reward_used', clientId, rewardId: reward.id, purchaseId: input.purchaseId });
  }
  if (redeem > 0) {
    out.ledger.push({
      clientId,
      type: 'redeem',
      amount: -redeem,
      purchaseId: input.purchaseId,
      staffId: input.staffId,
      reason: null,
      createdAt: now,
    });
    events.push({ type: 'points_redeemed', clientId, purchaseId: input.purchaseId, amount: redeem, balance: balanceBefore - redeem });
  }
  if (cashback > 0) {
    out.ledger.push({
      clientId,
      type: 'accrual',
      amount: cashback,
      purchaseId: input.purchaseId,
      staffId: input.staffId,
      reason: `${cashbackPct}% of ${cashbackBase}`,
      createdAt: now,
    });
    events.push({
      type: 'points_accrued',
      clientId,
      purchaseId: input.purchaseId,
      amount: cashback,
      balance: balanceBefore - redeem + cashback,
    });
  }

  // 5. Honeycomb.
  const hc = rules.honeycomb;
  const pos = cardPosition(rules, s);
  let cellSkipReason: PurchaseSummary['cellSkipReason'] = null;
  if (amount < hc.minPurchaseForCell) cellSkipReason = 'below_min_amount';
  else if (cellMovesOnDay(rules, s, now) >= hc.maxCellsPerDay) cellSkipReason = 'daily_limit';

  let cycle = pos.cycle;
  let cell = pos.filled;
  const unlocked: Reward[] = [];
  if (!cellSkipReason) {
    cell = pos.filled + 1;
    const move: CardMove = { clientId, purchaseId: input.purchaseId, cycle, cell, reason: 'purchase', createdAt: now, revertedAt: null };
    out.cardMoves.push(move);
    for (const cr of rewardsForCycle(rules, cycle).filter((r) => r.cell === cell)) {
      unlocked.push({
        id: rewardId(cycle, cell, input.purchaseId),
        clientId,
        cycle,
        cell,
        type: cr.type,
        value: cr.value ?? null,
        title: cr.title,
        status: 'available',
        unlockedByPurchase: input.purchaseId,
        usedInPurchase: null,
        unlockedAt: now,
        usedAt: null,
      });
    }
    const completed = cell >= hc.cells;
    const nextPos = completed ? { cycle: cycle + 1, filled: 0 } : { cycle, filled: cell };
    events.push({
      type: 'card_advanced',
      clientId,
      purchaseId: input.purchaseId,
      cycle,
      cell,
      purchasesToNextReward: purchasesToNextReward(rules, nextPos),
      cardCompleted: completed,
    });
    for (const r of unlocked) {
      events.push({ type: 'reward_unlocked', clientId, rewardId: r.id, cycle, cell, rewardType: r.type, title: r.title });
    }
  }
  out.rewardsUnlocked.push(...unlocked);

  // Purchase record (result filled below, after the level is known).
  const record: PurchaseRecord = {
    id: input.purchaseId,
    clientId,
    staffId: input.staffId,
    idempotencyKey: input.idempotencyKey,
    amount,
    lines: input.lines.map((l) => ({ ...l })),
    channel: input.channel,
    pointsRedeemed: redeem,
    discountApplied: discount,
    rewardUsedId: reward?.id ?? null,
    rulesVersion: rules.version,
    status: 'active',
    reversedReason: null,
    reversedBy: null,
    reversedAt: null,
    createdAt: now,
    result: null,
  };
  out.purchase = record;

  // 6. Level after the purchase.
  const after = applyOutcome(s, out);
  const levelAfter = deriveLevel(rules, after, now);
  if (levelAfter.index > levelBefore.index) {
    out.levelChange = { from: levelBefore.tier.id, to: levelAfter.tier.id };
    events.push({ type: 'level_up', clientId, from: levelBefore.tier.id, to: levelAfter.tier.id, cashbackPct: levelAfter.tier.cashbackPct });
  }

  record.result = {
    amount,
    discountApplied: discount,
    pointsRedeemed: redeem,
    paid,
    cashbackBase,
    cashbackPct,
    cashback,
    levelBefore: levelBefore.tier.id,
    levelAfter: levelAfter.tier.id,
    cellAdvanced: !cellSkipReason,
    cellSkipReason,
    cycle,
    cell,
    rewardsUnlocked: unlocked.map((r) => r.id),
    balanceAfter: balanceFromLedger(after.ledger),
  };
  out.events = events;
  return mergeOutcomes(expiry, out);
}
