// Makes sure the Mini App static folder exists, so `wrangler dev/deploy` never fails
// on a missing `assets.directory`. The real app is built by `npm run build -w apps/miniapp`
// into apps/miniapp/dist; until then a small placeholder page is served.
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dist = join(dirname(fileURLToPath(import.meta.url)), '..', '..', 'miniapp', 'dist');
const index = join(dist, 'index.html');
if (existsSync(index)) {
  console.log(`[ensure-assets] ${index} exists`);
} else {
  mkdirSync(dist, { recursive: true });
  writeFileSync(
    index,
    `<!doctype html>
<html lang="ru">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Honey Flowers</title>
<script src="https://telegram.org/js/telegram-web-app.js"></script>
<style>body{font-family:system-ui,sans-serif;margin:0;padding:32px 16px;text-align:center;background:#fff8e7;color:#3b2a10}</style>
</head>
<body>
<h1>🐝 Медовая карта</h1>
<p>Приложение ещё собирается. API работает: <a href="/health">/health</a></p>
<!-- placeholder generated by apps/worker/scripts/ensure-assets.mjs -->
</body>
</html>
`,
  );
  console.log(`[ensure-assets] created placeholder ${index}`);
}
