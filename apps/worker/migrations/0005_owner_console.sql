-- Owner web console ("Кабинет владельца"): browser login links, sessions, client base import,
-- and indexes for the console's analytics queries (apps/worker/src/console/*).

-- ---------------------------------------------------------------- browser login
-- One-time login links created by POST /api/owner/web-link. Only the SHA-256 of the
-- token is stored; the token itself lives in the URL fragment (#t=...) for <= 10 minutes
-- and is consumed atomically by POST /api/web/session (used_at set once).
CREATE TABLE web_link_tokens (
  token_hash   TEXT PRIMARY KEY,
  telegram_id  INTEGER NOT NULL,
  created_at   TEXT NOT NULL,
  expires_at   TEXT NOT NULL,
  used_at      TEXT
);
CREATE INDEX web_link_tokens_expires_idx ON web_link_tokens (expires_at);

-- Browser sessions are stateless HMAC-signed tokens (12 h). Each carries the owner's
-- session version; "Выйти" bumps the version, which revokes every session of that owner.
CREATE TABLE web_session_versions (
  telegram_id  INTEGER PRIMARY KEY,
  version      INTEGER NOT NULL DEFAULT 1 CHECK (version >= 1),
  updated_at   TEXT NOT NULL
);

-- ---------------------------------------------------------------- client base import
-- An imported client has a phone but no Telegram account yet: clients.telegram_id holds a
-- NEGATIVE placeholder (-<phone digits>, real Telegram user ids are positive). When the
-- real person shares that phone with the bot, the row is CLAIMED: telegram_id becomes
-- the real id and the balance / history stay (packages/service registerWithPhone).
CREATE TABLE import_batches (
  id              TEXT PRIMARY KEY,                 -- generated by the console, shared by all chunks of one file
  created_at      TEXT NOT NULL,
  updated_at      TEXT NOT NULL,
  created_by      TEXT NOT NULL,                    -- staff id / "tg:<id>" (TEST_MODE)
  file_name       TEXT,
  options         TEXT NOT NULL CHECK (json_valid(options)),
  rows_received   INTEGER NOT NULL DEFAULT 0,
  created_count   INTEGER NOT NULL DEFAULT 0,
  updated_count   INTEGER NOT NULL DEFAULT 0,
  skipped_count   INTEGER NOT NULL DEFAULT 0,
  honey_total     INTEGER NOT NULL DEFAULT 0,
  status          TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'undone')),
  undone_at       TEXT
);
CREATE INDEX import_batches_created_idx ON import_batches (created_at);

-- Clients CREATED by an import (one row per client, first batch wins) with the legacy
-- figures from the old base, kept for reference even if an option did not use them.
CREATE TABLE client_imports (
  client_id             TEXT PRIMARY KEY REFERENCES clients(id) ON DELETE CASCADE,
  batch_id              TEXT NOT NULL REFERENCES import_batches(id),
  legacy_balance        INTEGER,
  legacy_total          INTEGER,
  legacy_count          INTEGER,
  legacy_last_purchase  TEXT,
  created_at            TEXT NOT NULL
);
CREATE INDEX client_imports_batch_idx ON client_imports (batch_id);

-- Name / birthday an import filled in for clients that ALREADY existed (first values per batch),
-- so undoing the batch can put the old values back (only where the import's value is still there).
CREATE TABLE import_updates (
  batch_id      TEXT NOT NULL REFERENCES import_batches(id),
  client_id     TEXT NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
  old_name      TEXT,
  old_birthday  TEXT,
  new_name      TEXT,
  new_birthday  TEXT,
  created_at    TEXT NOT NULL,
  PRIMARY KEY (batch_id, client_id)
);
CREATE INDEX import_updates_client_idx ON import_updates (client_id);

-- Option "засчитать прошлые покупки в соты": an 'import' card move places the bee on
-- cell N without unlocking the gifts it passed. SQLite cannot alter a CHECK constraint,
-- so card_moves is rebuilt (nothing references card_moves, ids are preserved).
CREATE TABLE card_moves_new (
  id           INTEGER PRIMARY KEY AUTOINCREMENT,
  client_id    TEXT NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
  purchase_id  TEXT REFERENCES purchases(id) ON DELETE CASCADE,
  cycle        INTEGER NOT NULL CHECK (cycle >= 1),
  cell         INTEGER NOT NULL CHECK (cell >= 0),
  reason       TEXT NOT NULL DEFAULT 'purchase' CHECK (reason IN ('purchase', 'expiry_reset', 'import')),
  reverted_at  TEXT,
  created_at   TEXT NOT NULL,
  CONSTRAINT card_moves_kind CHECK (
    (reason = 'purchase' AND purchase_id IS NOT NULL AND cell >= 1) OR
    (reason = 'expiry_reset' AND purchase_id IS NULL AND cell = 0) OR
    (reason = 'import' AND purchase_id IS NULL AND cell >= 1)
  )
);
INSERT INTO card_moves_new (id, client_id, purchase_id, cycle, cell, reason, reverted_at, created_at)
  SELECT id, client_id, purchase_id, cycle, cell, reason, reverted_at, created_at FROM card_moves;
DROP TABLE card_moves;
ALTER TABLE card_moves_new RENAME TO card_moves;
CREATE INDEX card_moves_client_idx ON card_moves (client_id, id);
CREATE UNIQUE INDEX card_moves_purchase_uq ON card_moves (purchase_id) WHERE reverted_at IS NULL AND purchase_id IS NOT NULL;
CREATE UNIQUE INDEX card_moves_cell_uq ON card_moves (client_id, cycle, cell) WHERE reverted_at IS NULL AND reason = 'purchase';

-- ---------------------------------------------------------------- analytics indexes
-- Every index entry is a billed row write on each insert (Workers Free: 100k rows written / day),
-- so only indexes that change what the console reads are added. The ledger (the most written
-- table) gets none: its period scans use points_ledger_created_idx / points_ledger_standalone_idx.
-- Covering indexes on purchases: period aggregates (overview) and per-client sums / "bought
-- before?" probes (client list, repeat purchases) read index entries only.
CREATE INDEX purchases_active_period_cover ON purchases (status, created_at, client_id, amount);
CREATE INDEX purchases_client_cover ON purchases (status, client_id, created_at, amount);
-- Gifts opened / handed out in a period (rare writes).
CREATE INDEX rewards_unlocked_idx ON rewards (unlocked_at);
CREATE INDEX rewards_used_at_idx ON rewards (used_at) WHERE status = 'used';
